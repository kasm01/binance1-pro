def out(i,*,tiers,partial):
    entry=B[i]['o'];stop=entry*(1-.0299)
    # Each tier can fire once (on close), execution next bar open.
    arming_bar=None;peak=0.;floor=None;seen=-1;triggered=set()
    rest=1.;realized=0.;events=[];pending=[]
    def close_fraction(frac,price,reason,j):
        nonlocal rest,realized
        frac=min(frac,rest)
        if frac<=1e-10:return
        roi_pp=300*(price/entry-1)-FEE_ROI_PP
        realized+=frac*roi_pp
        rest=max(0.,rest-frac)
        events.append(dict(at_bar=j,reason=reason,closed_original_fraction=round(frac,8),
                           price=price,net_roi_pp_on_closed_slice=round(roi_pp,6)))
    final_reason='TIMEOUT'
    final_j=i
    for j in range(i,min(i+60,len(B)-1)):
        bar=B[j]
        # Stop gap precedes any pending scale-out fill.
        if bar['o']<=stop:
            close_fraction(rest,bar['o'],'STOP_GAP',j);final_reason='STOP_GAP';final_j=j;break
        # If already a closed-bar trailing trigger, close residual on
        # next OPEN rather than filling any other pending partial.
        if arming_bar=='TRAIL_EXIT_PENDING':
            close_fraction(rest,bar['o'],'TRAIL_NEXT_OPEN',j)
            final_reason='TRAIL_NEXT_OPEN';final_j=j;break
        # Partial orders generated by previous completed candle.
        # Simulate their combined execution at next open (optimistic fills).
        for k in pending:
            if rest<=1e-10:break
            close_fraction(FRACS[k],bar['o'],f'TIER_{k+1}_NEXT_OPEN',j)
        pending=[]
        if rest<=1e-10:
            final_reason='ALL_SLICES_NEXT_OPEN';final_j=j;break
        # Stop during current full 1m bar is the first touch, pessimistic.
        if bar['l']<=stop:
            close_fraction(rest,stop,'STOP_FIRST',j)
            final_reason='STOP_FIRST';final_j=j;break
        roi_close=300*(bar['c']/entry-1)
        peak=max(peak,roi_close)
        k=max((n for n,(arm,gb) in enumerate(tiers) if peak>=arm),default=-1)
        if k>=0:
            if arming_bar is None: arming_bar=j
            seen=max(seen,k)
            floor=max(peak-tiers[k][1],floor if floor is not None else float('-inf'))
            if partial:
                # Every crossed tier receives at most one fraction, no
                # historical tier can be repeatedly 'harvested'.
                pending=sorted(n for n in range(k+1) if n not in triggered)
                triggered.update(pending)
            if j>arming_bar and roi_close<=floor:
                arming_bar='TRAIL_EXIT_PENDING'
        final_j=j
    else:
        final_reason='TIMEOUT'
    # Finish after 60 bars with remaining quantity at last bar CLOSE.
    if rest>1e-10 and final_reason=='TIMEOUT':
        close_fraction(rest,B[final_j]['c'],'TIMEOUT',final_j)
    assert rest<1e-8,(rest,final_reason)
    assert abs(sum(z['closed_original_fraction'] for z in events)-1.)<1e-7
    return dict(exit_idx=final_j,reason=final_reason,
      total_net_roi_pp=round(realized,6),
      stages_reached=max(seen+1,0),number_of_partial_fills=sum('TIER_' in z['reason'] for z in events),
      realized_by_partial_roi_pp=round(sum(z['closed_original_fraction']*z['net_roi_pp_on_closed_slice']
        for z in events if 'TIER_' in z['reason']),6),
      fills=events)
def book(tiers,partial,broker=False):
    busy=-1;trades=[]
